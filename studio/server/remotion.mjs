// Everything that touches Remotion: the generated registry, bundling, stills, full renders,
// the live Remotion Studio process, and ffmpeg helpers for reference videos and audio.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawn, execFile} from 'node:child_process';
import {pathToFileURL} from 'node:url';
import {REEL, REEL_ENTRY, REEL_SRC_STUDIO, REMOTION_CLI, FFMPEG, FFPROBE, reelRequire} from './paths.mjs';

const load = (name) => import(pathToFileURL(reelRequire.resolve(name)).href);
const CHROMIUM = {gl: 'angle'}; // same as remotion.config.ts (the 3D scenes need a GPU-backed GL)

// ---------- registry: src/studio/registry.tsx lists every src/studio/<id>/index.tsx ----------
export const writeRegistry = () => {
  const ids = fs.existsSync(REEL_SRC_STUDIO)
    ? fs.readdirSync(REEL_SRC_STUDIO).filter((d) => fs.existsSync(path.join(REEL_SRC_STUDIO, d, 'index.tsx'))).sort()
    : [];
  const has = (id, file) => fs.existsSync(path.join(REEL_SRC_STUDIO, id, file));
  const imports = ids.map((id, i) => `import {COMPOSITIONS as P${i}} from './${id}';${has(id, 'audio.json') ? `\nimport A${i} from './${id}/audio.json';` : ''}${has(id, 'look.json') ? `\nimport L${i} from './${id}/look.json';` : ''}`).join('\n');
  const expr = (id, i) => { let e = `P${i}`; if (has(id, 'look.json')) e = `withLook(${e}, L${i} as LookConfig)`; if (has(id, 'audio.json')) e = `withAudio('${id}', ${e}, A${i} as AudioConfig)`; return e; };
  const list = ids.map((id, i) => `  ['${id}', ${expr(id, i)}],`).join('\n');
  const src = `// GENERATED by the Video Studio server: lists every src/studio/<id>/index.tsx. Do not edit by hand.
// audio.json adds the soundtrack (Audio tab); look.json adds the finishing layer (Look & feel tab).
import React from 'react';
import {Composition, Folder} from 'remotion';
import type {StudioComp} from './types';
import {withStudioAudio, type AudioConfig} from './StudioAudio';
import {withStudioLook, type LookConfig} from './StudioLook';
${imports}

const withAudio = (id: string, comps: StudioComp[], audio: AudioConfig): StudioComp[] =>
  comps.map((c) => (c.id === \`Studio-\${id}\` ? {...c, component: withStudioAudio(c.component, audio)} : c));
const withLook = (comps: StudioComp[], look: LookConfig): StudioComp[] =>
  comps.map((c) => ({...c, component: withStudioLook(c.component, look, c.id.endsWith('-concepts'))}));

const PROJECTS: [string, StudioComp[]][] = [
${list}
];

export const StudioCompositions: React.FC = () => (
  <>
    {PROJECTS.map(([id, comps]) => (
      <Folder key={id} name={\`studio-\${id}\`}>
        {comps.map((c) => <Composition key={c.id} {...c} />)}
      </Folder>
    ))}
  </>
);
`;
  const file = path.join(REEL_SRC_STUDIO, 'registry.tsx');
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== src) fs.writeFileSync(file, src);
  return ids;
};

// ---------- bundle (one at a time; webpack caching keeps repeats fast) ----------
let queue = Promise.resolve();
const serial = (fn) => { const p = queue.then(fn, fn); queue = p.catch(() => {}); return p; };

export const bundleSite = (onProgress) => serial(async () => {
  writeRegistry();
  const {bundle} = await load('@remotion/bundler');
  return bundle({entryPoint: REEL_ENTRY, rootDir: REEL, publicDir: path.join(REEL, 'public'), onProgress: (p) => onProgress?.(p / 100), enableCaching: true});
});

// ---------- stills: [{composition, frame, props, out}] rendered with one bundle and one browser ----------
export const renderStills = async (specs, {onProgress, serveUrl} = {}) => {
  const {openBrowser, selectComposition, renderStill} = await load('@remotion/renderer');
  serveUrl ??= await bundleSite((p) => onProgress?.({stage: 'bundling', progress: p}));
  const browser = await openBrowser('chrome', {chromiumOptions: CHROMIUM});
  const done = [];
  try {
    for (const [i, s] of specs.entries()) {
      onProgress?.({stage: 'stills', progress: i / specs.length, file: s.out});
      fs.mkdirSync(path.dirname(s.out), {recursive: true});
      const inputProps = s.props ?? {};
      try {
        const composition = await selectComposition({serveUrl, id: s.composition, inputProps, puppeteerInstance: browser, chromiumOptions: CHROMIUM});
        const frame = Math.max(0, Math.min(composition.durationInFrames - 1, Math.round(s.frame ?? 0)));
        await renderStill({serveUrl, composition, output: s.out, frame, inputProps, imageFormat: 'png', scale: s.scale ?? 1, puppeteerInstance: browser, chromiumOptions: CHROMIUM, overwrite: true});
        done.push({...s, ok: true});
      } catch (e) {
        done.push({...s, ok: false, error: String(e.message ?? e).split('\n')[0]});
      }
    }
  } finally {
    await browser.close({silent: true}).catch(() => {});
  }
  onProgress?.({stage: 'stills', progress: 1});
  return done;
};

// ---------- full render to MP4 ----------
export const renderVideo = async ({composition: id, out, props = {}, scale = 1, onProgress, signal}) => {
  const {selectComposition, renderMedia, makeCancelSignal} = await load('@remotion/renderer');
  const serveUrl = await bundleSite((p) => onProgress?.({stage: 'bundling', progress: p}));
  const composition = await selectComposition({serveUrl, id, inputProps: props, chromiumOptions: CHROMIUM});
  const cancel = makeCancelSignal();
  signal?.addEventListener('abort', () => cancel.cancel());
  fs.mkdirSync(path.dirname(out), {recursive: true});
  await renderMedia({
    serveUrl, composition, inputProps: props, codec: 'h264', outputLocation: out, crf: 18, jpegQuality: 95, scale,
    chromiumOptions: CHROMIUM, cancelSignal: cancel.cancelSignal, overwrite: true,
    onProgress: ({progress, renderedFrames, stitchStage}) => onProgress?.({stage: stitchStage === 'muxing' ? 'muxing' : 'rendering', progress, frames: renderedFrames, total: composition.durationInFrames}),
  });
  return {out, durationInFrames: composition.durationInFrames, fps: composition.fps, width: composition.width, height: composition.height};
};

// ---------- live Remotion Studio (hot-reloads while the agent edits code) ----------
let studioProc = null;
export const STUDIO_PORT = Number(process.env.REMOTION_STUDIO_PORT ?? 3100);
export const startRemotionStudio = (log = () => {}) => {
  if (studioProc) return;
  writeRegistry();
  studioProc = spawn(process.execPath, [REMOTION_CLI, 'studio', '--port', String(STUDIO_PORT), '--no-open'], {cwd: REEL, env: {...process.env, BROWSER: 'none'}});
  studioProc.stdout.on('data', (d) => log(String(d)));
  studioProc.stderr.on('data', (d) => log(String(d)));
  studioProc.on('exit', () => { studioProc = null; });
};
export const stopRemotionStudio = () => studioProc?.kill();

// ---------- ffmpeg helpers ----------
const run = (bin, args) => new Promise((res, rej) => execFile(bin, args, {maxBuffer: 1 << 26, windowsHide: true}, (e, out, err) => (e ? rej(new Error(String(err || e.message).slice(-600))) : res(String(out)))));

export const probe = async (file) => {
  const j = JSON.parse(await run(FFPROBE, ['-v', 'error', '-print_format', 'json', '-show_format', '-show_streams', file]));
  const v = j.streams.find((s) => s.codec_type === 'video');
  const a = j.streams.find((s) => s.codec_type === 'audio');
  const [n, d] = (v?.avg_frame_rate ?? '0/1').split('/').map(Number);
  return {duration: Number(j.format.duration) || 0, width: v?.width, height: v?.height, fps: d ? Math.round((n / d) * 100) / 100 : undefined, hasAudio: !!a, hasVideo: !!v && !/^(mjpeg|png)$/.test(v.codec_name)};
};

// Reference video -> one small frame every second, named by its time, plus audio for transcription.
// (Remotion's ffmpeg has no fps/tile filters, so we seek per frame.)
export const extractReference = async (video, outDir) => {
  fs.mkdirSync(outDir, {recursive: true});
  const info = await probe(video);
  const every = 1;
  const frames = [], seenFrames = new Set();
  let duplicates = 0;
  for (let t = Math.min(0.2, info.duration / 2); t < info.duration; t += every) {
    const name = `f-${t.toFixed(1).padStart(5, '0')}s.jpg`;
    const framePath = path.join(outDir, name);
    await run(FFMPEG, ['-y', '-v', 'error', '-ss', t.toFixed(2), '-i', video, '-frames:v', '1', '-vf', 'scale=480:-2', '-q:v', '4', framePath]).then(() => {
      const hash = crypto.createHash('sha256').update(fs.readFileSync(framePath)).digest('hex');
      if (seenFrames.has(hash)) { fs.rmSync(framePath, {force: true}); duplicates++; }
      else { seenFrames.add(hash); frames.push(name); }
    }, () => {});
  }
  if (info.hasAudio) await run(FFMPEG, ['-y', '-v', 'error', '-i', video, '-vn', '-ac', '1', '-ar', '16000', path.join(outDir, 'audio.wav')]).catch(() => {});
  fs.writeFileSync(path.join(outDir, 'README.txt'), `Frames of ${path.basename(video)} (${info.duration.toFixed(1)} s, ${info.width}x${info.height}, ${info.fps} fps), sampled every ${every} s; identical frames removed (${duplicates}); file names show the original time.\n${info.hasAudio ? 'audio.wav is its soundtrack (transcribe it for the script and pacing).\n' : ''}`);
  return {...info, every, frames, duplicates};
};

export const toWav16k = (input, out) => run(FFMPEG, ['-y', '-v', 'error', '-i', input, '-vn', '-ac', '1', '-ar', '16000', '-c:a', 'pcm_s16le', out]);

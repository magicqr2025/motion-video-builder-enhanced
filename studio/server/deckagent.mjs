// Visual PPT: "tell Claude what to change" for a deck, like the chat on a video.
//   GET  /api/decks/:id/chat         what was said and done so far, and whether Claude is working now
//   POST /api/decks/:id/chat         {message}  start a request (it runs in the background; the page polls the GET)
//   POST /api/decks/:id/chat/stop    stop it
// Claude may only read and edit files inside the deck folder, and cannot run commands. After it finishes the studio rebuilds the deck itself.
import fs from 'node:fs';
import path from 'node:path';
import {query} from '@anthropic-ai/claude-agent-sdk';
import {DATA} from './paths.mjs';
import {claudeEnv} from './agent.mjs';
import {aiConfig, aiRuntime} from './settings.mjs';
import {startProcess, endProcess, addProcessTokens, activityLog} from './activity.mjs';

const fail = (status, message) => Object.assign(new Error(message), {status});
const CHATS = path.join(DATA, '_decks-chat');
const MAX_LOG = 300;
const runs = new Map(); // deckId -> {ac, startedAt}
export const deckBusy = (id) => runs.has(id);
export const busyDecks = () => [...runs.keys()];

const logFile = (id) => path.join(CHATS, `${id.replace(/[^\w-]/g, '_')}.json`);
const readLog = (id) => { try { return JSON.parse(fs.readFileSync(logFile(id), 'utf8')); } catch { return []; } };
const addLog = (id, kind, text) => {
  const log = readLog(id);
  log.push({t: Date.now(), kind, text: String(text).slice(0, 4000)});
  fs.mkdirSync(CHATS, {recursive: true});
  fs.writeFileSync(logFile(id), JSON.stringify(log.slice(-MAX_LOG)));
};

const inside = (dir, file) => { const r = path.relative(dir, path.resolve(dir, String(file ?? ''))); return !!r && !r.startsWith('..') && !path.isAbsolute(r) && !/(^|[\\/])(node_modules|\.git)([\\/]|$)/.test(r); };
const GENERATED = (d) => new Set((d.build ?? []).map((b) => path.resolve(d.dir, b.out)));

// Only these tools, only inside the deck folder. No shell, no web, no other folders.
const permit = (d) => async (tool, input) => {
  const deny = (message) => ({behavior: 'deny', message});
  if (['Read', 'Write', 'Edit', 'MultiEdit'].includes(tool)) {
    const f = input.file_path ?? '';
    if (!inside(d.dir, path.isAbsolute(f) ? path.relative(d.dir, f) : f)) return deny(`Only files inside ${d.dir} can be used.`);
    if (tool !== 'Read' && GENERATED(d).has(path.resolve(d.dir, f))) return deny('That file is generated by the build. Change the source in src/ instead; the studio rebuilds after you finish.');
    return {behavior: 'allow', updatedInput: input};
  }
  if (tool === 'Glob' || tool === 'Grep') {
    if (input.path && !inside(d.dir, path.isAbsolute(input.path) ? path.relative(d.dir, input.path) : input.path) && path.resolve(d.dir, input.path) !== d.dir) return deny(`Only ${d.dir} can be searched.`);
    return {behavior: 'allow', updatedInput: input};
  }
  if (tool === 'TodoWrite') return {behavior: 'allow', updatedInput: input};
  return deny('This panel only allows reading and editing the deck’s own files. Commands and web access are off; the studio rebuilds the deck after you finish.');
};

const systemFor = (d) => `You are editing a browser slide deck for the user, from the "Visual PPT" page of MotionStudio.
The deck is the current folder: ${d.dir}. It is "${d.title}".${d.description ? ` About it: ${d.description}` : ''}
${d.build?.length
    ? `How it is built: all slide content (text, prices, structure) is HTML inside template strings in src/slides.js; the engine is src/core.js; styles are style.css and night.css. ${d.build.map((b) => `${b.entry} -> ${b.out}`).join(', ')} are bundled into the generated files ${d.build.map((b) => b.out).join(' and ')}. NEVER edit the generated files; edit the sources. You cannot run commands: the studio rebuilds the deck by itself when you finish, so do not try to build.`
    : 'It has no build step: edit its .html, .css and .js files directly.'}
Rules: make the smallest change that does what the user asked and keep the design as it is. Keep text short enough to fit a 16:9 slide. Do not invent facts, prices or testimonials: if you need a number or name the user did not give, use a clear [placeholder] and say so. Only touch files inside this folder. If the request is unclear, ask one short question instead of guessing.
When you finish, reply in one to three plain sentences, in simple words, saying exactly what you changed and in which slide. Never mention file names unless the user asks.`;

const toolText = (name, i = {}) => {
  const f = (p) => String(p ?? '').split(/[\\/]/).slice(-2).join('/');
  if (name === 'Read') return `Reading ${f(i.file_path)}`;
  if (name === 'Edit' || name === 'MultiEdit') return `Changing ${f(i.file_path)}`;
  if (name === 'Write') return `Writing ${f(i.file_path)}`;
  if (name === 'Glob' || name === 'Grep') return `Searching the deck${i.pattern ? ` for “${String(i.pattern).slice(0, 40)}”` : ''}`;
  return name;
};

const run = async (d, message, {rebuild, touch}) => {
  const ac = new AbortController(); ac.startedAt = Date.now();
  runs.set(d.id, ac);
  const cfg = aiConfig(), rt = aiRuntime(cfg);
  const proc = startProcess({kind: 'ai', label: `Visual PPT · ${d.title}: ${message.replace(/\s+/g, ' ').slice(0, 110)}`, projectId: null, model: rt.model || rt.engine, where: rt.where});
  const seen = {input: 0, output: 0, cacheRead: 0, cacheWrite: 0, context: 0};
  let usageDone = false, ok = false, failure = '';
  try {
    const env = await claudeEnv();
    const q = query({
      prompt: message,
      options: {
        cwd: d.dir, resume: d.sessionId ?? undefined, systemPrompt: {type: 'preset', preset: 'claude_code', append: systemFor(d)}, settingSources: [],
        permissionMode: 'default', canUseTool: permit(d), abortController: ac, model: cfg.model || process.env.STUDIO_MODEL || undefined, env, title: `MotionStudio · deck · ${d.title}`,
      },
    });
    for await (const m of q) {
      if (m.type === 'assistant') {
        if (m.error || m.message?.model === '<synthetic>') continue;
        const u = m.message?.usage;
        if (u) { seen.input += u.input_tokens ?? 0; seen.output += u.output_tokens ?? 0; seen.cacheRead += u.cache_read_input_tokens ?? 0; seen.cacheWrite += u.cache_creation_input_tokens ?? 0; }
        if (m.session_id && d.sessionId !== m.session_id) { d.sessionId = m.session_id; touch(d, false); }
        if (m.parent_tool_use_id) continue;
        for (const b of m.message.content ?? []) {
          if (b.type === 'text' && b.text.trim()) addLog(d.id, 'text', b.text.trim());
          else if (b.type === 'tool_use') addLog(d.id, 'tool', toolText(b.name, b.input));
        }
      } else if (m.type === 'result') {
        ok = m.subtype === 'success' && !m.is_error;
        const ru = m.usage ?? {};
        addProcessTokens(proc, {input: ru.input_tokens ?? 0, output: ru.output_tokens ?? 0, cacheRead: ru.cache_read_input_tokens ?? 0, cacheWrite: ru.cache_creation_input_tokens ?? 0, context: seen.context}, m.total_cost_usd ?? 0);
        usageDone = true;
        if (!ok) failure = m.result || m.errors?.join('\n') || `Stopped (${m.subtype})`;
      }
    }
  } catch (e) { failure = ac.signal.aborted ? 'Stopped.' : String(e.message ?? e); }
  if (!usageDone && (seen.input || seen.output || seen.cacheRead || seen.cacheWrite)) addProcessTokens(proc, seen, 0);
  if (failure) {
    const hint = /\blog ?in\b|not (logged|signed) in|authenticat|\b401\b|credential/i.test(failure) ? '\nSign in to Claude Code on this PC: run "claude" in a terminal and type /login, then try again.' : '';
    addLog(d.id, 'error', failure + hint);
  }
  if (ok && d.build?.length) {
    try { const t = Date.now(); await rebuild(d); addLog(d.id, 'done', `Rebuilt the deck (${((Date.now() - t) / 1000).toFixed(1)}s). Press View, or refresh the open tab, to see the change.`); }
    catch (e) { addLog(d.id, 'error', `Claude finished, but the rebuild failed: ${e.message}`); ok = false; }
  } else if (ok) addLog(d.id, 'done', 'Done. Press View, or refresh the open tab, to see the change.');
  endProcess(proc, {status: ac.signal.aborted ? 'stopped' : ok ? 'done' : 'error', error: ok ? null : failure});
  touch(d, true);
  runs.delete(d.id);
  activityLog(`Visual PPT: ${ok ? 'finished a change to' : 'could not finish a change to'} “${d.title}”.`, {source: 'save', level: ok ? 'ok' : 'warn'});
};

export const mountDeckChat = (app, {wrap, need, touch, rebuild}) => {
  const localDeck = (id) => { const d = need(id); if (d.kind === 'online') throw fail(400, 'This deck lives on claude.ai. Open it to edit it there.'); if (!fs.existsSync(d.dir)) throw fail(400, 'The deck folder is missing.'); return d; };
  app.get('/api/decks/:id/chat', wrap(async (req, res) => { const d = need(req.params.id); res.json({busy: runs.has(d.id), startedAt: runs.get(d.id)?.startedAt ?? null, log: readLog(d.id)}); }));
  app.post('/api/decks/:id/chat', wrap(async (req, res) => {
    const d = localDeck(req.params.id);
    const message = String(req.body?.message ?? '').trim();
    if (!message) throw fail(400, 'Write what you want changed first.');
    if (message.length > 4000) throw fail(400, 'That message is too long (limit 4000 characters).');
    if (runs.has(d.id)) throw fail(409, 'Claude is still working on this deck. Stop it or wait.');
    addLog(d.id, 'user', message);
    run(d, message, {rebuild, touch}).catch((e) => { addLog(d.id, 'error', String(e.message ?? e)); runs.delete(d.id); });
    res.json({ok: true});
  }));
  app.post('/api/decks/:id/chat/stop', wrap(async (req, res) => { runs.get(need(req.params.id).id)?.abort(); res.json({ok: true}); }));
  app.delete('/api/decks/:id/chat', wrap(async (req, res) => { const d = need(req.params.id); if (runs.has(d.id)) throw fail(409, 'Stop Claude first.'); fs.rmSync(logFile(d.id), {force: true}); d.sessionId = null; touch(d, false); res.json({ok: true}); }));
};

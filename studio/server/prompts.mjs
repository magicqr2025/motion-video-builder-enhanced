const fmtBrief = (p) => {
  const b = p.brief;
  const lines = [
    ['Title', p.title], ['Idea / goal', b.idea], ['Audience', b.audience], ['Call to action', b.cta],
    ['Language', b.language], ['Script / voiceover text', b.script], ['Key on-screen text', b.onScreen],
    ['Size', `${b.width}x${b.height} @ ${b.fps} fps`], ['Target duration', b.durationSec ? `${b.durationSec} s` : 'follow the voiceover / content'],
    ['Colours', (b.colors ?? []).join(', ')], ['Style words', b.style], ['Captions', b.captions], ['Links to study', b.links], ['Notes / do & don\'t', b.notes],
  ];
  return lines.filter(([, v]) => v && String(v).trim()).map(([k, v]) => `- **${k}:** ${String(v).trim().replace(/\n/g, '\n  ')}`).join('\n');
};

const fmtAssets = (p) => p.assets.length
  ? p.assets.map((a) => `- ${a.role}: public/studio/${p.id}/${a.file}${a.info?.duration ? ` (${a.info.duration.toFixed(1)} s${a.info.width ? `, ${a.info.width}x${a.info.height}` : ''})` : ''}${a.refDir ? ` -> frames in data/${p.id}/${a.refDir}/` : ''}${a.transcript ? ` -> transcript data/${p.id}/${a.transcript}` : ''}${a.note ? ` (note: ${a.note})` : ''}`).join('\n')
  : '- (none uploaded)';

const fmtPreset = (p) => {
  const pr = getPreset(p.presetId);
  if (!pr) return 'No preset: design freely. You can borrow from any existing video in src/. Available presets for inspiration:\n' + listPresets().map((x) => `- ${x.name}: ${x.tagline}`).join('\n');
  return `**${pr.name}**: ${pr.tagline}\nReference composition: ${pr.example?.composition}. Reuse these files: ${pr.reuse.join(', ')}\nRecipe:\n${pr.recipe.map((r) => `- ${r}`).join('\n')}`;
};

const fmtBrand = (p) => {
  const br = getBrand(p.brief.brandId);
  if (!br) return 'Custom brand: use the colours from the brief.';
  return `**${br.name}** palette ${Object.entries(br.palette).map(([k, v]) => `${k} ${v}`).join(', ')}; logo public/${br.logo}${br.endVideo ? `; end video public/${br.endVideo}` : ''}; fonts ${br.fonts.join(', ')}; site ${br.site}; email ${br.email}.\nAssets in public/: ${br.assets.join('; ')}\nRules:\n${br.rules.map((r) => `- ${r}`).join('\n')}`;
};


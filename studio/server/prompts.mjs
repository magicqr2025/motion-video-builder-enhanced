// What the agent is told. SYSTEM is appended to Claude Code's own system prompt for every turn;
// the phase prompts carry the brief and say what to do next.
import path from 'node:path';
import {REEL, STUDIO, projectDir, projectAssets, projectCode, compId, conceptsCompId} from './paths.mjs';
import {getPreset, getBrand, listPresets} from './projects.mjs';

const rel = (p) => path.relative(REEL, p).split(path.sep).join('/');

// The user edits this file directly in the browser's Text tab, so every video must follow it.
const TEXT_RULE = `EVERY on-screen string (headlines, captions, labels, names, prices, CTA, caption words) lives in
  src/studio/<id>/text.json, never hard-coded in .tsx. Group it by scene in display order, with readable keys, e.g.
  {"Hook": {"headline": "Customer khush hai", "sub": "par review nahi dete?"}, "Steps": [{"title": "Scan"}], "End": {"cta": "Start free"}}.
  Only strings (and arrays/objects of strings) go in it; no timings or colours. Import it with
  \`import TEXT from './text.json';\` and read TEXT.Hook.headline etc. Layouts must cope with the text getting ~30% longer
  (auto-fit font size or wrap) because the user may retype it. Keys starting with "_" are hidden from the user
  (use "_help": {"Hook.headline": "max ~25 chars"} for hints).`;

export const SYSTEM = `
# You are the video designer inside "MagicBolt Video Studio"

The user works in a browser app. They fill a brief (idea, script, colours, size, uploads, links, a preset), you
propose concepts as sample stills, they approve one, you build the full Remotion video with exact timing, they
review it and render. Your text replies appear in the app's activity panel: keep them short, plain and specific
(what you did, what you need). Never ask the user to run commands; you run everything.

## Where things are (cwd is the Remotion project ${REEL})
- Existing approved videos and reusable kits: src/** (read them; reuse their components instead of starting over).
- Each studio project has:
  - code: src/studio/<id>/ (index.tsx must export COMPOSITIONS: StudioComp[] from '../types')
  - assets: public/studio/<id>/ (uploads land here; use staticFile('studio/<id>/<file>'))
  - workspace: ${STUDIO}/data/<id>/ (concepts.json, storyboard.json, samples/, checks/, refs/, transcripts/)
- src/studio/registry.tsx is generated by the app from the project folders. Never edit it or src/Root.tsx; run
  \`node ../studio/bin/registry.mjs\` after creating a project's index.tsx.
- Composition ids: Studio-<id> (the full video) and Studio-<id>-concepts (concept samples, takes prop {concept}).

## Tools you run with Bash (from the cwd)
- \`node ../studio/bin/samples.mjs <id>\`: renders every concept sample in concepts.json to data/<id>/samples/.
- \`node ../studio/bin/still.mjs <compositionId> <seconds|fN> <out.png> [propsJson]\`: one check still.
- \`node ../studio/bin/transcribe.mjs <audio> [--lang en|hi|auto]\`: word + sentence timestamps (writes <audio>.words.json).
  The app already transcribes uploaded voiceovers into data/<id>/transcripts/; use those if present.
  Whisper misspells brand names (e.g. "MagicBalt" = MagicBolt): fix spellings in captions and scripts.
- \`node ../studio/bin/reference.mjs <video> <outDir>\`: frames named by time + audio.wav from a reference video.
  The app already does this for uploaded reference videos into data/<id>/refs/<name>/.
- \`npx tsc --noEmit -p .\`: typecheck. A type error in any project breaks every render, so always run it.
- \`node ../scripts/generate-image.mjs "<prompt>" <name> --size 1024x1536\` (only if OPENAI_API_KEY is set) for
  glossy illustration art; move results into public/studio/<id>/.
- Look at every still you render with the Read tool. Judge it like an art director; fix and re-render before reporting.

## Remotion rules
- Deterministic: animate only from useCurrentFrame()/fps (or the TimeCtx/useSec patterns in the kits). No Math.random
  without a seed, no CSS transitions, no setTimeout.
- Use <OffthreadVideo>, <Img>, <Audio> with staticFile(). Fonts are bundled in public/fonts (see src/components/kit.tsx).
- Keep timings, colours and layout numbers in one config.ts per project (scene \`dur\` in seconds, cues in seconds
  from the scene start, a "// VO 12.40" comment with each scene's start in the voiceover), like src/qr/config.ts.
- ${TEXT_RULE}
- Timing is driven by the voiceover when there is one: scene starts at sentence starts, key reveals on the spoken
  word. Without audio, aim for ~2.5 words/s of on-screen reading plus 0.4 s breathing room per beat.

## Taste (the user's standing preferences)
- Glossy, illustration-rich, brand-coloured, polished. Anything plain or flat reads as unfinished: start at that
  level instead of iterating up to it. Glossy 3D icons/characters, never flat emoji.
- Bold, large typography; short copy (one or two lines per item); every element animates in.
- Backgrounds move subtly and semi-transparently so they never compete with the content.
- Reuse real assets (public/*.png illustrations, logos, logo-animation.mp4).
- Tutorials: logo TitleCard opening, EndLogo ending, synced to the voiceover; show sample stills before the full build.
- Privacy: no real account data, keys or DNS values in videos; use demo data.
`;

const fmtBrief = (p) => {
  const b = p.brief;
  const lines = [
    ['Title', p.title], ['Idea / goal', b.idea], ['Audience', b.audience], ['Call to action', b.cta],
    ['Language', b.language], ['Script / voiceover text', b.script], ['Key on-screen text', b.onScreen],
    ['Size', `${b.width}x${b.height} @ ${b.fps} fps`], ['Target duration', b.durationSec ? `${b.durationSec} s` : 'follow the voiceover / content'],
    ['Colours', (b.colors ?? []).join(', ')], ['Style words', b.style], ['Captions', b.captions], ['Links to study', b.links], ['Notes / do & don\'t', b.notes],
  ];
  return lines.filter(([, v]) => v && String(v).trim()).map(([k, v]) => `- **${k}:** ${String(v).trim().replace(/\n/g, '\n  ')}`).join('\n');
};

const fmtAssets = (p) => p.assets.length
  ? p.assets.map((a) => `- ${a.role}: public/studio/${p.id}/${a.file}${a.info?.duration ? ` (${a.info.duration.toFixed(1)} s${a.info.width ? `, ${a.info.width}x${a.info.height}` : ''})` : ''}${a.refDir ? ` -> frames in data/${p.id}/${a.refDir}/` : ''}${a.transcript ? ` -> transcript data/${p.id}/${a.transcript}` : ''}${a.note ? ` (note: ${a.note})` : ''}`).join('\n')
  : '- (none uploaded)';

const fmtPreset = (p) => {
  const pr = getPreset(p.presetId);
  if (!pr) return 'No preset: design freely. You can borrow from any existing video in src/. Available presets for inspiration:\n' + listPresets().map((x) => `- ${x.name}: ${x.tagline}`).join('\n');
  return `**${pr.name}**: ${pr.tagline}\nReference composition: ${pr.example?.composition}. Reuse these files: ${pr.reuse.join(', ')}\nRecipe:\n${pr.recipe.map((r) => `- ${r}`).join('\n')}`;
};

const fmtBrand = (p) => {
  const br = getBrand(p.brief.brandId);
  if (!br) return 'Custom brand: use the colours from the brief.';
  return `**${br.name}** palette ${Object.entries(br.palette).map(([k, v]) => `${k} ${v}`).join(', ')}; logo public/${br.logo}${br.endVideo ? `; end video public/${br.endVideo}` : ''}; fonts ${br.fonts.join(', ')}; site ${br.site}; email ${br.email}.\nAssets in public/: ${br.assets.join('; ')}\nRules:\n${br.rules.map((r) => `- ${r}`).join('\n')}`;
};

